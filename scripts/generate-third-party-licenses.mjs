import { createHash } from "node:crypto";
import { lstat, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const lockPath = join(projectRoot, "package-lock.json");
const outputPath = join(projectRoot, "THIRD_PARTY_LICENSES.md");
const evidencePattern = /^(?:licen[cs]e|unlicense|copying|notice)(?:[._-].*|$)/i;

function markdownCell(value) {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function compareStrings(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function codeFenceFor(text) {
  const runs = text.match(/`+/g) ?? [];
  const longest = runs.reduce((maximum, run) => Math.max(maximum, run.length), 0);
  return "`".repeat(Math.max(3, longest + 1));
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function collectInventory() {
  const lock = JSON.parse(await readFile(lockPath, "utf8"));

  if (lock.lockfileVersion !== 3 || typeof lock.packages !== "object") {
    throw new Error("The license inventory requires an npm lockfileVersion 3 package lock.");
  }

  const packages = [];
  for (const [packagePath, locked] of Object.entries(lock.packages)) {
    if (packagePath === "" || locked.dev === true) {
      continue;
    }

    if (!packagePath.startsWith("node_modules/")) {
      throw new Error(`Unsupported production package path in package-lock.json: ${packagePath}`);
    }

    const installedPath = join(projectRoot, packagePath);
    const manifestPath = join(installedPath, "package.json");
    let manifest;
    try {
      manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    } catch (error) {
      throw new Error(
        `Cannot read installed production package manifest ${relative(projectRoot, manifestPath)}. Run npm ci first.`,
        { cause: error },
      );
    }

    if (typeof manifest.name !== "string" || manifest.name.length === 0) {
      throw new Error(`${packagePath} has no package name.`);
    }
    if (manifest.version !== locked.version) {
      throw new Error(
        `${manifest.name} installed version ${JSON.stringify(manifest.version)} does not match lockfile version ${JSON.stringify(locked.version)}.`,
      );
    }
    if (typeof locked.license !== "string" || locked.license.length === 0) {
      throw new Error(`${manifest.name}@${manifest.version} has no license declaration in package-lock.json.`);
    }
    if (manifest.license !== locked.license) {
      throw new Error(
        `${manifest.name}@${manifest.version} declares ${JSON.stringify(manifest.license)} in its installed manifest but ${JSON.stringify(locked.license)} in package-lock.json.`,
      );
    }

    const evidenceNames = (await readdir(installedPath))
      .filter((name) => evidencePattern.test(name))
      .sort(compareStrings);
    if (evidenceNames.length === 0) {
      throw new Error(
        `${manifest.name}@${manifest.version} contains no top-level LICENSE, LICENCE, UNLICENSE, COPYING, or NOTICE evidence file.`,
      );
    }

    const evidence = [];
    for (const evidenceName of evidenceNames) {
      const evidencePath = join(installedPath, evidenceName);
      const evidenceStat = await lstat(evidencePath);
      if (!evidenceStat.isFile()) {
        throw new Error(
          `${manifest.name}@${manifest.version}/${evidenceName} is not a regular file.`,
        );
      }
      const bytes = await readFile(evidencePath);
      if (bytes.length === 0) {
        throw new Error(`${manifest.name}@${manifest.version}/${evidenceName} is empty.`);
      }
      const text = bytes.toString("utf8");
      if (Buffer.from(text, "utf8").compare(bytes) !== 0) {
        throw new Error(`${manifest.name}@${manifest.version}/${evidenceName} is not UTF-8 text.`);
      }
      evidence.push({
        name: evidenceName,
        sha256: sha256(bytes),
        text: text.replaceAll("\r\n", "\n").replaceAll("\r", "\n").replace(/\n*$/, "\n"),
      });
    }

    packages.push({
      name: manifest.name,
      version: manifest.version,
      license: manifest.license,
      evidence,
    });
  }

  return packages.sort((left, right) => {
    const byName = compareStrings(left.name, right.name);
    return byName || compareStrings(left.version, right.version);
  });
}

function renderInventory(packages) {
  const evidenceByHash = new Map();
  const lines = [
    "<!-- Generated by scripts/generate-third-party-licenses.mjs. Do not edit by hand. -->",
    "",
    "# Production npm dependency licenses",
    "",
    "This deterministic inventory covers every non-development npm package in",
    "`package-lock.json`, as installed by `npm ci`. Each evidence hash is calculated",
    "from the exact license or notice file bundled in that package's npm artifact.",
    "Development-only packages and GlassBridge's own Apache-2.0 license are excluded.",
    "",
    `**Production package count:** ${packages.length}`,
    "",
    "| Package | Version | Declared license | Bundled evidence |",
    "| --- | --- | --- | --- |",
  ];

  for (const entry of packages) {
    const evidenceLinks = [];
    for (const evidence of entry.evidence) {
      const reference = `${entry.name}@${entry.version} (${evidence.name})`;
      const existing = evidenceByHash.get(evidence.sha256);
      if (existing) {
        if (existing.text !== evidence.text) {
          throw new Error(`SHA-256 collision while inventorying ${reference}.`);
        }
        existing.references.push(reference);
      } else {
        evidenceByHash.set(evidence.sha256, {
          text: evidence.text,
          references: [reference],
        });
      }
      evidenceLinks.push(`[${evidence.name}](#sha-256-${evidence.sha256}) \`${evidence.sha256}\``);
    }
    lines.push(
      `| \`${markdownCell(entry.name)}\` | \`${markdownCell(entry.version)}\` | \`${markdownCell(entry.license)}\` | ${evidenceLinks.join("<br>")} |`,
    );
  }

  lines.push("", "## Bundled license texts", "");
  for (const [hash, evidence] of [...evidenceByHash].sort(([left], [right]) => compareStrings(left, right))) {
    const fence = codeFenceFor(evidence.text);
    lines.push(
      `### SHA-256 ${hash}`,
      "",
      `Used by: ${evidence.references.sort(compareStrings).map((reference) => `\`${reference}\``).join(", ")}`,
      "",
      `${fence}text`,
      evidence.text.replace(/\n$/, ""),
      fence,
      "",
    );
  }

  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

const mode = process.argv[2] ?? "--check";
if (!["--check", "--print", "--write"].includes(mode) || process.argv.length > 3) {
  throw new Error("Usage: node scripts/generate-third-party-licenses.mjs [--check|--print|--write]");
}

const rendered = renderInventory(await collectInventory());
if (mode === "--print") {
  process.stdout.write(rendered);
} else if (mode === "--write") {
  await writeFile(outputPath, rendered, "utf8");
  console.log(`Wrote ${relative(projectRoot, outputPath)}.`);
} else {
  let committed;
  try {
    committed = await readFile(outputPath, "utf8");
  } catch (error) {
    throw new Error("THIRD_PARTY_LICENSES.md is missing. Run npm run licenses:generate.", {
      cause: error,
    });
  }
  if (committed !== rendered) {
    throw new Error(
      "THIRD_PARTY_LICENSES.md is stale or the production license evidence changed. Run npm run licenses:generate and review the diff.",
    );
  }
  console.log("Production dependency license inventory is complete and current.");
}
